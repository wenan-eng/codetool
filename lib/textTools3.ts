const CIRCLED_UPPER_START = 0x24b6
const CIRCLED_LOWER_START = 0x24d0
const CIRCLED_DIGIT_START = 0x2460

export function circleLetters(text: string): string {
  return text.split("").map(ch => {
    const code = ch.charCodeAt(0)
    if (code >= 65 && code <= 90) return String.fromCodePoint(CIRCLED_UPPER_START + code - 65)
    if (code >= 97 && code <= 122) return String.fromCodePoint(CIRCLED_LOWER_START + code - 97)
    if (code >= 48 && code <= 57) {
      const n = code - 48
      if (n === 0) return "⓪"
      return String.fromCodePoint(CIRCLED_DIGIT_START + n - 1)
    }
    return ch
  }).join("")
}

export interface RandomStringOptions {
  minLength: number
  maxLength: number
  count: number
  charset?: string
}

const DEFAULT_CHARSET = "abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"

export function generateRandomStrings(opts: RandomStringOptions): string[] {
  const charset = opts.charset && opts.charset.length > 0 ? opts.charset : DEFAULT_CHARSET
  const min = Math.max(1, Math.min(opts.minLength, opts.maxLength))
  const max = Math.min(charset.length > 0 ? 1024 : 1, Math.max(opts.minLength, opts.maxLength))
  const count = Math.min(Math.max(1, opts.count), 10000)
  const out: string[] = []
  for (let i = 0; i < count; i++) {
    const len = min + Math.floor(Math.random() * (max - min + 1))
    let s = ""
    for (let j = 0; j < len; j++) s += charset[Math.floor(Math.random() * charset.length)]
    out.push(s)
  }
  return out
}

export interface SequenceOptions {
  start: number
  step: number
  count: number
  padWidth: number
  prefix: string
  suffix: string
}

export function generateSequence(opts: SequenceOptions): string[] {
  const count = Math.min(Math.max(1, opts.count), 100000)
  const out: string[] = []
  for (let i = 0; i < count; i++) {
    let n = String(opts.start + i * opts.step)
    if (opts.padWidth > 0) n = n.padStart(opts.padWidth, "0")
    out.push(`${opts.prefix}${n}${opts.suffix}`)
  }
  return out
}

export interface FormatOptions {
  indent: boolean
  trimSpaces: boolean
  removeEmoji: boolean
  removeHtml: boolean
}

export function formatText(text: string, opts: FormatOptions): string {
  let out = text
  if (opts.removeHtml) out = out.replace(/<[^>]*>/g, "")
  if (opts.removeEmoji) out = out.replace(/[\u{1F000}-\u{1FAFF}]|[\u{2600}-\u{27BF}]|[\u{FE00}-\u{FE0F}]|\u{200D}/gu, "")
  if (opts.trimSpaces) out = out.replace(/[ \t]+/g, " ").replace(/ ?\n ?/g, "\n").replace(/\n{3,}/g, "\n\n")
  if (opts.indent) out = out.split(/\n/).map(line => line.trim()).filter(Boolean).map(line => `　　${line}`).join("\n")
  return out.replace(/[\s]+$/, "")
}
